"""Owned synthetic reference files. Requires pinned psdtags path as argument.
No Photato code is imported. NumPy2.4.1/tifffile2026.1.28/imagecodecs2026.1.14.
"""
import hashlib,importlib.util,json,pathlib,sys
import numpy as np
import tifffile
out=pathlib.Path(sys.argv[2]) if len(sys.argv)>2 else pathlib.Path(__file__).resolve().parent
out.mkdir(parents=True,exist_ok=True)
spec=importlib.util.spec_from_file_location('psdtags',sys.argv[1]);p=importlib.util.module_from_spec(spec);sys.modules['psdtags']=p;spec.loader.exec_module(p)
records=[]
for depth,dtype,key in [(8,np.uint8,p.PsdKey.LAYER),(16,np.uint16,p.PsdKey.LAYER_16),(32,np.float32,p.PsdKey.LAYER_32)]:
 def samples(h,w):
  i=np.arange(h*w*4,dtype=np.uint32).reshape(h,w,4)
  if depth==32:
   a=(i.astype(np.float32)-12)/8;a[...,3]=(i[...,3]%5).astype(np.float32)/4
   a[0,0,0]=np.float32(-0.0)
  else:a=((i*1553+77)%(256 if depth==8 else 65536)).astype(dtype)
  return a
 base=samples(4,5);top=samples(2,3);mask=np.array([[0,1,1],[1,1,0]],dtype=dtype)*(1 if depth==32 else (255 if depth==8 else 65535))
 for name,a in [('base',base),('top',top),('mask',mask)]:
  (out/f'{depth}-{name}.raw').write_bytes(a.astype(np.dtype(dtype).newbyteorder('<')).tobytes())
 for order,fmt in [('big',p.PsdFormat.BE32BIT),('little',p.PsdFormat.LE32BIT)]:
  for compression in range(4):
   def channels(a):
    return [p.PsdChannel(p.PsdChannelId(i if i<3 else -1),p.PsdCompressionType(compression),a[...,i]) for i in range(4)]
   baseLayer=p.PsdLayer('Base',channels(base),p.PsdRectangle(0,0,4,5),info=[p.PsdString(p.PsdKey.UNICODE_LAYER_NAME,'Base Ω')])
   marker=p.PsdLayer('End',[],p.PsdRectangle(0,0,0,0),info=[p.PsdSectionDividerSetting(p.PsdSectionDividerType.BOUNDING_SECTION_DIVIDER)])
   topLayer=p.PsdLayer('Top',channels(top)+[p.PsdChannel(p.PsdChannelId.USER_LAYER_MASK,p.PsdCompressionType(compression),mask)],p.PsdRectangle(1,-1,3,2),mask=p.PsdLayerMask(default_color=1,rectangle=p.PsdRectangle(1,-1,3,2)),opacity=153,blendmode=p.PsdBlendMode.MULTIPLY,flags=p.PsdLayerFlag.PHOTOSHOP5|p.PsdLayerFlag.VISIBLE,info=[p.PsdString(p.PsdKey.UNICODE_LAYER_NAME,'Crème 层'),p.PsdInteger(p.PsdKey.PROTECTED_SETTING,1),p.PsdInteger(p.PsdKey.LAYER_ID,123)])
   group=p.PsdLayer('Group',[],p.PsdRectangle(0,0,0,0),info=[p.PsdString(p.PsdKey.UNICODE_LAYER_NAME,'Layers'),p.PsdSectionDividerSetting(p.PsdSectionDividerType.OPEN_FOLDER,p.PsdBlendMode.PASS_THROUGH)])
   source=p.TiffImageSourceData(fmt,p.PsdLayers(key,[baseLayer,marker,topLayer,group],True),p.PsdUserMask())
   # Deliberately unrelated white cache catches accidental flattening.
   cache=np.full((4,5,4),1 if depth==32 else (255 if depth==8 else 65535),dtype=dtype)
   path=out/f'{depth}-{order}-{compression}.tiff'
   tifffile.imwrite(path,cache,byteorder='>' if order=='big' else '<',photometric='rgb',extrasamples='unassalpha',metadata=None,resolution=(144,144),resolutionunit='inch',extratags=[source.tifftag()])
   parsed=p.TiffImageSourceData.fromtiff(path)
   for idx,expected in [(0,base),(2,top)]:
    for j in range(4):np.testing.assert_array_equal(parsed.layers.layers[idx].channels[j].data,expected[...,j])
   np.testing.assert_array_equal(parsed.layers.layers[2].channels[4].data,mask)
   records.append({'file':path.name,'depth':depth,'order':order,'compression':compression,'sha256':hashlib.sha256(path.read_bytes()).hexdigest()})
   if compression==3:
    source.info=[p.PsdEmpty(p.PsdKey.SAVING_MERGED_TRANSPARENCY2)]
    marked=out/f'{depth}-{order}-marker.tiff'
    tifffile.imwrite(marked,cache,byteorder='>' if order=='big' else '<',photometric='rgb',extrasamples='unassalpha',metadata=None,resolution=(144,144),resolutionunit='inch',extratags=[source.tifftag()])
    parsed=p.TiffImageSourceData.fromtiff(marked)
    assert parsed.info[0].key==p.PsdKey.SAVING_MERGED_TRANSPARENCY2
    for j in range(4):np.testing.assert_array_equal(parsed.layers.layers[2].channels[j].data,top[...,j])
    records.append({'file':marked.name,'depth':depth,'order':order,'compression':compression,'marker':'MTrn','sha256':hashlib.sha256(marked.read_bytes()).hexdigest()})
(out/'provenance.json').write_text(json.dumps({'origin':'Owned synthetic numerical fixtures; generated by independent BSD-licensed psdtags; no Photoshop output claim','psdtags_revision':'3b72663b375b60dbadaedfa6eefe5bb4c5cd9e7a','psdtags_sha256':hashlib.sha256(pathlib.Path(sys.argv[1]).read_bytes()).hexdigest(),'dependencies':{'numpy':np.__version__,'tifffile':tifffile.__version__,'imagecodecs':'2026.1.14'},'fixtures':records},indent=2)+'\n')
print('Generated and independently read',len(records),'layered TIFF fixtures')
