/// Menu inventory observed in Photoshop 2026, with its factory macOS shortcuts.
/// Product/system exceptions and reference hashes: docs/MENU_PARITY_REFERENCES.json.
struct EditorMenuNode {
  let title: String
  var children: [Self]?
  var key = ""
  var modifiers: NSEvent.ModifierFlags = []
  static let separator = Self(title: "-")
  static func item(_ title: String, key: String = "", modifiers: NSEvent.ModifierFlags = []) -> Self
  {
    Self(title: title, key: key, modifiers: modifiers)
  }
  static func menu(_ title: String, _ children: [Self]) -> Self {
    Self(title: title, children: children)
  }
}

