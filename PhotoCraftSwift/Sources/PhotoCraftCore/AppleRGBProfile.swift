import Foundation

extension NativeModeProfile {
  /// Independently written ICC v2 matrix/TRC profile. No Adobe profile bytes,
  /// executable code or SDK are redistributed. See APPLE_RGB_PROOF.md for the
  /// published colorimetry and the independently observed ICC rounding values.
  public static func appleRGB(depth: PixelDepth = .u16) throws -> Data {
    try atDepth(appleRGBProfile, mode: .rgb, depth: depth)
  }

  private static let appleRGBProfile: Data = {
    func number(_ value: UInt32) -> Data {
      Data([UInt8(truncatingIfNeeded: value >> 24), UInt8(truncatingIfNeeded: value >> 16),
        UInt8(truncatingIfNeeded: value >> 8), UInt8(truncatingIfNeeded: value)])
    }
    func signature(_ text: String) -> Data { Data(text.utf8) }
    func xyz(_ values: [UInt32]) -> Data {
      signature("XYZ ") + number(0) + values.reduce(into: Data()) { $0.append(number($1)) }
    }
    let name = Data("Apple RGB\0".utf8)
    // ICC v2 textDescriptionType: ASCII, absent Unicode, absent ScriptCode.
    let description = signature("desc") + number(0) + number(UInt32(name.count)) + name
      + Data(repeating: 0, count: 8 + 2 + 1 + 67)
    let curve = signature("curv") + number(0) + number(1) + Data([0x01, 0xcd])
    let tags: [(String, Data)] = [
      ("desc", description),
      ("cprt", signature("text") + number(0) + Data("Generated by Photato from standard Apple RGB colorimetry.\0".utf8)),
      ("wtpt", xyz([62289, 65536, 71372])), ("bkpt", xyz([0, 0, 0])),
      ("rXYZ", xyz([31165, 16722, 1209])),
      ("gXYZ", xyz([22264, 44079, 7427])),
      ("bXYZ", xyz([9762, 4735, 45424])),
      ("rTRC", curve), ("gTRC", curve), ("bTRC", curve)
    ]
    var header = Data(repeating: 0, count: 128)
    func put(_ offset: Int, _ data: Data) { header.replaceSubrange(offset..<offset + data.count, with: data) }
    put(8, number(0x02100000)); put(12, signature("mntr")); put(16, signature("RGB ")); put(20, signature("XYZ "))
    // Fixed creation metadata makes identical requests stable across launches.
    put(24, Data([0x07, 0xea, 0, 11, 0, 9, 0, 0, 0, 0, 0, 0]))
    put(36, signature("acsp")); put(40, signature("APPL")); put(64, number(1))
    put(68, number(63190) + number(65536) + number(54061)); put(80, signature("Phto"))
    var table = number(UInt32(tags.count)), payload = Data()
    for (key, data) in tags {
      table.append(signature(key)); table.append(number(UInt32(132 + tags.count * 12 + payload.count)))
      table.append(number(UInt32(data.count))); payload.append(data)
      while payload.count % 4 != 0 { payload.append(0) }
    }
    put(0, number(UInt32(header.count + table.count + payload.count)))
    return header + table + payload
  }()
}
